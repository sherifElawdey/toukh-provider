export const LANGS = ['ar', 'en'];

/** `auto` follows Chrome's UI language; anything not Arabic is English. */
export function resolveLang(setting, uiLanguage = '') {
  if (setting === 'ar' || setting === 'en') return setting;
  return String(uiLanguage).toLowerCase().startsWith('ar') ? 'ar' : 'en';
}

export function translator(lang) {
  const table = STRINGS[lang] || STRINGS.en;
  return (key, params = {}) => {
    let s = table[key] ?? STRINGS.en[key] ?? key;
    for (const [k, v] of Object.entries(params)) s = s.replaceAll(`{${k}}`, String(v));
    return s;
  };
}

export function hasKey(key) {
  return Object.prototype.hasOwnProperty.call(STRINGS.en, key);
}

